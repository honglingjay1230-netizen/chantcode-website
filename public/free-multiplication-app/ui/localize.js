function preserveOuterWhitespace(original, translated) {
  const leading = original.match(/^\s*/)?.[0] ?? '';
  const trailing = original.match(/\s*$/)?.[0] ?? '';
  return `${leading}${translated}${trailing}`;
}

export function translateText(value, language = activeAppLanguage) {
  if (typeof value !== 'string') return value;
  const normalizePunctuation = (text) => text
    .replaceAll('，', ',')
    .replaceAll('。', '.')
    .replaceAll('：', ':')
    .replaceAll('；', ';')
    .replaceAll('？', '?')
    .replaceAll('！', '!')
    .replaceAll('（', '(')
    .replaceAll('）', ')');
  const trimmed = value.trim();
  if (!trimmed) return value;

  if (normalizeAppLanguage(language) === 'zh') {
    if (HAN_TEXT.test(value)) return value;
    const exactChinese = REVERSE_PHRASES.get(trimmed);
    if (exactChinese) return preserveOuterWhitespace(value, exactChinese);

    for (const [pattern, replacement] of DYNAMIC_REVERSE_TRANSLATIONS) {
      if (pattern.test(trimmed)) {
        pattern.lastIndex = 0;
        return preserveOuterWhitespace(value, trimmed.replace(pattern, replacement));
      }
    }

    return value;
  }

  if (!HAN_TEXT.test(value)) return normalizePunctuation(value);

  const exact = PHRASES.get(trimmed);
  if (exact) return preserveOuterWhitespace(value, exact);

  for (const [pattern, replacement] of DYNAMIC_TRANSLATIONS) {
    if (pattern.test(trimmed)) {
      pattern.lastIndex = 0;
      return preserveOuterWhitespace(value, trimmed.replace(pattern, replacement));
    }
  }

  let translated = trimmed;
  for (const [source, target] of SORTED_PHRASES) {
    translated = translated.split(source).join(target);
  }
  return preserveOuterWhitespace(value, normalizePunctuation(translated));
}

const LOCALIZED_ATTRIBUTES = ['aria-label', 'title', 'alt', 'placeholder'];

function localizeNode(node) {
  if (!node) return;
  if (node.nodeType === Node.TEXT_NODE) {
    const translated = translateText(node.nodeValue);
    if (translated !== node.nodeValue) node.nodeValue = translated;
    return;
  }
  if (node.nodeType !== Node.ELEMENT_NODE && node.nodeType !== Node.DOCUMENT_FRAGMENT_NODE) return;
  if (node.nodeType === Node.ELEMENT_NODE) {
    LOCALIZED_ATTRIBUTES.forEach((attribute) => {
      if (!node.hasAttribute(attribute)) return;
      const current = node.getAttribute(attribute);
      const translated = translateText(current);
      if (translated !== current) node.setAttribute(attribute, translated);
    });
  }
  node.childNodes.forEach(localizeNode);
}

function startLocalization() {
  document.documentElement.lang = activeAppLanguage === 'zh' ? 'zh-CN' : 'en';
  document.title = translateText(document.title);
  localizeNode(document.body);
  const observer = new MutationObserver((mutations) => {
    mutations.forEach((mutation) => {
      if (mutation.type === 'characterData') localizeNode(mutation.target);
      mutation.addedNodes?.forEach(localizeNode);
      if (mutation.type === 'attributes') localizeNode(mutation.target);
    });
  });
  observer.observe(document.body, {
    subtree: true,
    childList: true,
    characterData: true,
    attributes: true,
    attributeFilter: LOCALIZED_ATTRIBUTES,
  });
}

if (typeof document !== 'undefined') {
  if (document.body) startLocalization();
  else document.addEventListener('DOMContentLoaded', startLocalization, { once: true });
}
