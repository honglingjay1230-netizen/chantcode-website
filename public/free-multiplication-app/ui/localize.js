const HAN_TEXT = /[\u3400-\u9fff]/;
export const APP_LANGUAGE_STORAGE_KEY = 'chantcode.app-language.v1';

function normalizeAppLanguage(value) {
  return value === 'zh' ? 'zh' : 'en';
}

function readStoredAppLanguage() {
  try {
    return normalizeAppLanguage(globalThis.localStorage?.getItem(APP_LANGUAGE_STORAGE_KEY));
  } catch {
    return 'en';
  }
}

let activeAppLanguage = readStoredAppLanguage();

export function getAppLanguage() {
  return activeAppLanguage;
}

export function setAppLanguage(value, { reload = true } = {}) {
  activeAppLanguage = normalizeAppLanguage(value);
  try { globalThis.localStorage?.setItem(APP_LANGUAGE_STORAGE_KEY, activeAppLanguage); } catch {
    // Language switching must still work for the current session when storage is unavailable.
  }
  if (typeof document !== 'undefined') {
    document.documentElement.lang = activeAppLanguage === 'zh' ? 'zh-CN' : 'en';
  }
  if (reload) globalThis.location?.reload?.();
  return activeAppLanguage;
}

